import '../l10n/l10n.dart';

/// The Quran collections' own text - the notes on the duas of the Quran
/// (`quran_duas.dart`) and on the verses about Imam Ali (a.s.)
/// (`quran_ali_verses.dart`) and Imam al-Mahdi (a.t.f.s.)
/// (`quran_mahdi_verses.dart`), and the prophets' stories
/// (`quran_prophet_stories.dart`) - in one of the app's other languages.
///
/// The English stays where it is, in those files; this only lays a language
/// over it. Everything is keyed by the entry's first verse ("2:127"), never
/// by its English, except the prophets' headings, which are keyed by the
/// English heading their stories are grouped under.
///
/// If you add, change or remove an entry in one of those files, do the same
/// for every language here: `test/quran_collections_i18n_test.dart` fails
/// until each covers exactly the entries there are.
class QuranCollectionsText {
  const QuranCollectionsText({
    required this.duas,
    required this.imamAli,
    required this.imamMahdi,
    required this.prophets,
    required this.stories,
  });

  /// Each `QuranDua.note`.
  final Map<String, String> duas;

  /// Each note of `quranAliVerses`.
  final Map<String, String> imamAli;

  /// Each note of `quranMahdiVerses`.
  final Map<String, String> imamMahdi;

  /// Each `QuranStory.prophet` heading, keyed by the English.
  final Map<String, String> prophets;

  /// Each `QuranStory.title`.
  final Map<String, String> stories;
}

/// The collections' text in [languageCode] - by default the app language -
