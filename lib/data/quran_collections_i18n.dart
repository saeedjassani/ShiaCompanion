///
/// Follows the app language, like the calendar and the hadith of the day:
/// these notes sit in the app's own lists and verse menu rather than in a
/// zikr's translation.
QuranCollectionsText? quranCollectionsText([String? languageCode]) =>
    quranCollectionsTranslations[languageCode ?? L10n.current.localeName];

